// Builds the buyer and seller guides from data/guides.json:
//   guides.html              the guides hub (both guides + three Gulf Coast essentials)
//   guides/<slug>.html       one page per guide (buying, selling)
//   data/guides-posts.json   every step's ready-made Facebook post, with a link to that step
//
// Edit the words in data/guides.json, not the pages. Runs automatically from GitHub
// (.github/workflows/build-guides.yml) whenever data/guides.json changes.
// Run by hand with:  node scripts/build-guides.mjs

import { readFile, writeFile, mkdir } from "node:fs/promises";

const ROOT = new URL("../", import.meta.url);
const file = (p) => new URL(p, ROOT);

// The address people use to reach the site. Change to https://billtemplerealtor.com once the domain points at it.
const SITE_URL = "https://bill-temple-realtor.vercel.app";

const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const pad = (n) => String(n).padStart(2, "0");
const isExternal = (href) => /^https?:/.test(href);
const linkTag = (l) =>
  `<a href="${esc(l.href)}"${isExternal(l.href) ? ' rel="noopener" target="_blank"' : ""}>${esc(l.label)}${isExternal(l.href) ? ' <span aria-hidden="true">↗</span><span class="sr-only"> (opens in a new tab)</span>' : ""}</a>`;
const longDate = (iso) => new Date(iso + "T12:00:00Z").toLocaleDateString("en-US", { month: "long", year: "numeric", timeZone: "UTC" });

function head(title, description, path) {
  return `<!doctype html>
<!-- Built by scripts/build-guides.mjs. Do not edit this file: change data/guides.json instead. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <base href="/">
  <title>${esc(title)} | Bill Temple, Realtor</title>
  <meta name="description" content="${esc(description)}">
  <link rel="canonical" href="${SITE_URL}/${path}">
  <meta property="og:title" content="${esc(title)} | Bill Temple, Realtor">
  <meta property="og:description" content="${esc(description)}">
  <meta property="og:type" content="article">
  <meta property="og:url" content="${SITE_URL}/${path}">
  <link rel="stylesheet" href="css/styles.css">
  <link rel="stylesheet" href="forms/forms.css">
</head>`;
}

const FOOT = `
  <div id="site-footer"></div>
  <script src="js/site.js"></script>
  <script src="js/guide-question.js"></script>
</body>
</html>
`;

function finePrint(reviewed, what = "This guide is") {
  return `<p class="hv-fine">${what} general information about buying and selling homes in Mississippi, last reviewed ${longDate(reviewed)}. It is not legal, tax or insurance advice, and laws, forms, programs and insurance rules change. For advice about your situation, talk with a Mississippi real estate attorney, a tax professional or a licensed insurance agent.</p>
          <p class="fair-housing"><span data-site="agentName">Bill Temple</span> and <span data-site="brokerage">his brokerage</span> are committed to equal housing opportunity. Every buyer is welcome to look at homes anywhere, and every seller's home is marketed to everyone.</p>`;
}

// The "Related" band: home value, market update, neighborhoods, and the other guide.
function related(current, guides) {
  const other = current && guides.find((g) => g.slug !== current);
  const cards = [
    ["home-value.html", "Free estimate", "What's my home worth?", "Tell me about your home and get a personal value estimate, usually within one business day."],
    ["market.html", "Updated weekly", "Gulf Coast market update", "Prices, homes for sale, days on market and mortgage rates, by county."],
    ["neighborhoods.html", "Seven towns", "Neighborhood guides", "Homes for sale, typical prices, schools and commutes from Bay St. Louis to Ocean Springs."],
  ];
  if (other) cards.push([`guides/${other.slug}.html`, other.short, other.heading, other.card]);
  return `
    <section class="alt">
      <div class="container">
        <p class="eyebrow">Keep going</p>
        <h2>More tools for your move</h2>
        <div class="form-links guide-related">
${cards.map(([href, tag, title, text]) => `          <a href="${href}"><b>${esc(tag)}</b><strong>${esc(title)}</strong><span>${esc(text)}</span></a>`).join("\n")}
        </div>
      </div>
    </section>`;
}

