function stepHtml(s, i) {
  const parts = [`          <p class="guide-summary">${esc(s.summary)}</p>`];
  for (const p of s.body) parts.push(`          <p>${esc(p)}</p>`);
  if (s.checklist?.length) parts.push(`          <ul class="guide-check">\n${s.checklist.map((c) => `            <li>${esc(c)}</li>`).join("\n")}\n          </ul>`);
  if (s.local) parts.push(`          <aside class="guide-local"><p class="eyebrow">On the Coast</p><p>${esc(s.local)}</p></aside>`);
  if (s.links?.length) parts.push(`          <p class="guide-links">${s.links.map(linkTag).join("")}</p>`);
  return `        <article class="guide-step" id="${esc(s.id)}">
          <span class="guide-num" aria-hidden="true">${pad(i + 1)}</span>
          <h2><span class="sr-only">Step ${i + 1}: </span>${esc(s.title)}</h2>
${parts.join("\n")}
        </article>`;
}

function guidePage(g, data) {
  const toc = g.steps.map((s, i) => `            <li><a href="guides/${g.slug}.html#${esc(s.id)}"><span>${pad(i + 1)}</span>${esc(s.title)}</a></li>`).join("\n");
  return `${head(g.title, g.description, `guides/${g.slug}.html`)}
<body>
  <div id="site-header"></div>

  <main class="market guide">
    <section class="market-top">
      <div class="container">
        <p class="eyebrow"><a href="guides.html">Buyer and seller guides</a> · ${esc(g.short)}</p>
        <h1>${esc(g.heading)}</h1>
        <p class="market-lede">${esc(g.lede)}</p>
        <blockquote class="guide-take"><p>${esc(g.billsTake)}</p><footer>Bill Temple, Realtor</footer></blockquote>
        <div class="actions"><a class="btn" href="guides/${g.slug}.html#ask">Ask Bill a question</a><a class="btn secondary" href="guides/${g.slug}.html#${esc(g.steps[0].id)}">Start with step 1</a></div>
      </div>
    </section>

    <div class="container guide-layout">
      <nav class="guide-toc" aria-label="Steps in this guide">
        <p class="eyebrow">${g.steps.length} steps</p>
        <ol>
${toc}
        </ol>
      </nav>
      <div class="guide-steps">
${g.steps.map(stepHtml).join("\n")}
        <div class="market-sources guide-fine">
          ${finePrint(data.reviewed)}
        </div>
      </div>
    </div>
${related(g.slug, data.guides)}
${contact(g.short)}
  </main>
${FOOT}`;
}

function hubPage(data) {
  const h = data.hub;
  const cards = data.guides.map((g) => `          <a class="guide-card" href="guides/${g.slug}.html">
            <small>${esc(g.short)} · ${g.steps.length} steps</small>
            <strong>${esc(g.heading)}</strong>
            <span>${esc(g.card)}</span>
            <ol>${g.steps.slice(0, 4).map((s) => `<li>${esc(s.title)}</li>`).join("")}<li>…and ${g.steps.length - 4} more</li></ol>
            <em>Read the ${esc(g.short.toLowerCase())} →</em>
          </a>`).join("\n");
  const essentials = h.essentials.map((e) => `          <li><strong>${esc(e.title)}</strong><span>${esc(e.text)}</span>${e.link ? linkTag(e.link) : ""}</li>`).join("\n");
  return `${head(h.title, h.description, "guides.html")}
<body>
  <div id="site-header"></div>

  <main class="market guide">
    <section class="market-top">
      <div class="container">
        <p class="eyebrow">${esc(h.eyebrow)}</p>
        <h1>${esc(h.heading)}</h1>
        <p class="market-lede">${esc(h.lede)}</p>
      </div>
    </section>

    <section class="guide-hub">
      <div class="container">
        <div class="guide-cards">
${cards}
        </div>
      </div>
    </section>

    <section class="alt">
      <div class="container">
        <p class="eyebrow">What's different on the Coast</p>
        <h2>Three things to know before you start</h2>
        <ul class="places guide-essentials">
${essentials}
        </ul>
        <div class="market-sources">
          ${finePrint(data.reviewed, "These guides are")}
        </div>
      </div>
    </section>
${related("", data.guides)}
${contact("Guides")}
  </main>
${FOOT}`;
}

function posts(data) {
  const out = [];
  for (const g of data.guides) {
    g.steps.forEach((s, i) => {
      out.push({
        id: `${g.slug}-${s.id}`,
        guide: g.short,
        step: i + 1,
        title: s.title,
        url: `${SITE_URL}/guides/${g.slug}.html#${s.id}`,
        socialPost: `${s.socialPost}\n\n${g.short}, step ${i + 1}: ${SITE_URL}/guides/${g.slug}.html#${s.id}`,
      });
    });
  }
  return { _readme: "Built by scripts/build-guides.mjs from data/guides.json. One ready-made Facebook post per guide step.", reviewed: data.reviewed, posts: out };
}

const data = JSON.parse(await readFile(file("data/guides.json"), "utf8"));
for (const g of data.guides) {
  for (const s of g.steps) {
    if (!s.id || !s.title || !s.summary || !Array.isArray(s.body) || !s.socialPost) {
      throw new Error(`${g.slug}: step "${s.id || s.title}" needs id, title, summary, body and socialPost`);
    }
  }
}
await mkdir(file("guides/"), { recursive: true });
await writeFile(file("guides.html"), hubPage(data));
for (const g of data.guides) await writeFile(file(`guides/${g.slug}.html`), guidePage(g, data));
await writeFile(file("data/guides-posts.json"), JSON.stringify(posts(data), null, 2) + "\n");
console.log(`Built guides.html and ${data.guides.map((g) => `guides/${g.slug}.html`).join(", ")}`);
